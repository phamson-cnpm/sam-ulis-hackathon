
"""Cơ sở dữ liệu kiểm tra được tạo bằng Alembic (alembic upgrade head, core/migrate.py) như trên máy chủ thật.
Cấu trúc bảng sau khi nâng cấp phải khớp hoàn toàn với models/ (giống lệnh `alembic check`)."""
from alembic import command
from alembic.script import ScriptDirectory
from sqlalchemy import text

from core.migrate import alembic_config


async def test_cau_truc_bang_khop_models():
    command.check(alembic_config())  # có chỗ lệch thì báo lỗi AutogenerateDiffsDetected


async def test_dang_o_ban_moi_nhat(db):
    head = ScriptDirectory.from_config(alembic_config()).get_current_head()
    version = (await db.execute(text("SELECT version_num FROM alembic_version"))).scalar_one()
    assert version == head
